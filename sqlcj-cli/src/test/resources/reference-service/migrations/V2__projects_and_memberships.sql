-- Projects, the membership role, and the organization billing address.

CREATE TYPE membership_role AS ENUM ('viewer', 'member', 'owner');

CREATE TYPE postal_address AS
(
    street      text,
    city        text,
    postal_code text,
    country     text
);

CREATE TABLE projects
(
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint      NOT NULL REFERENCES organizations (id),
    code            varchar(8)  NOT NULL,
    name            text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE memberships
(
    organization_id bigint          NOT NULL REFERENCES organizations (id),
    user_id         bigint          NOT NULL REFERENCES users (id),
    role            membership_role NOT NULL DEFAULT 'member',
    created_at      timestamptz     NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, user_id)
);

ALTER TABLE organizations ADD COLUMN billing_address postal_address;
