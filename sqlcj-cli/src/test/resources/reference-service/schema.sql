-- The reference service schema as the migration history leaves it, written
-- directly: every type and table in its final shape, with no ALTER statement.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE DOMAIN email_address AS citext;

CREATE TYPE membership_role AS ENUM ('viewer', 'member', 'maintainer', 'owner');

CREATE TYPE task_status AS ENUM ('open', 'doing', 'blocked', 'done');

CREATE TYPE postal_address AS
(
    street      text,
    city        text,
    postal_code text,
    country     text
);

CREATE SEQUENCE audit_log_id_seq;

CREATE TABLE organizations
(
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name             text        NOT NULL,
    preferences      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at       timestamptz NOT NULL DEFAULT now(),
    billing_address  postal_address,
    retention_period interval
);

CREATE TABLE users
(
    id              bigserial PRIMARY KEY,
    organization_id bigint        NOT NULL REFERENCES organizations (id),
    email           email_address NOT NULL,
    handle          citext,
    display_name    text          NOT NULL,
    last_login_ip   inet,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    deleted_at      timestamptz
);

CREATE UNIQUE INDEX users_live_handle_key ON users (organization_id, handle) WHERE deleted_at IS NULL;

CREATE TABLE projects
(
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint      NOT NULL REFERENCES organizations (id),
    code            varchar(16) NOT NULL,
    name            text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE memberships
(
    organization_id bigint          NOT NULL REFERENCES organizations (id),
    user_id         bigint          NOT NULL REFERENCES users (id),
    role            membership_role NOT NULL DEFAULT 'member',
    created_at      timestamptz     NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, user_id)
);

CREATE TABLE tasks
(
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id     bigint      NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    title          text        NOT NULL,
    status         task_status NOT NULL DEFAULT 'open',
    priority       smallint    NOT NULL DEFAULT 2,
    labels         text[]      NOT NULL DEFAULT '{}',
    metadata       jsonb,
    version        integer     NOT NULL DEFAULT 1,
    estimate_hours numeric,
    title_length   integer GENERATED ALWAYS AS (length(title)) STORED,
    created_at     timestamptz NOT NULL DEFAULT now(),
    assignee_id    bigint REFERENCES users (id) ON DELETE SET NULL,
    CHECK (priority BETWEEN 1 AND 5)
);

CREATE TABLE comments
(
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    task_id    bigint      NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    author_id  bigint      NOT NULL REFERENCES users (id),
    body       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE time_entries
(
    id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    task_id bigint    NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    during  tstzrange NOT NULL,
    EXCLUDE USING gist (task_id WITH =, during WITH &&)
);

CREATE TABLE audit_log
(
    id          bigint      NOT NULL DEFAULT nextval('audit_log_id_seq'),
    occurred_at timestamptz NOT NULL,
    actor_id    bigint,
    action      text        NOT NULL,
    detail      jsonb,
    request_id  uuid,
    PRIMARY KEY (id, occurred_at)
) PARTITION BY RANGE (occurred_at);

CREATE TABLE audit_log_2026 PARTITION OF audit_log
    FOR VALUES FROM ('2026-01-01 00:00:00+00') TO ('2027-01-01 00:00:00+00');

CREATE TABLE audit_log_default PARTITION OF audit_log DEFAULT;

CREATE TABLE audit_log_archive
(
    id          bigint      NOT NULL DEFAULT nextval('audit_log_id_seq'),
    occurred_at timestamptz NOT NULL,
    actor_id    bigint,
    action      text        NOT NULL,
    detail      jsonb
);

CREATE SCHEMA reporting;

CREATE TABLE reporting.projects
(
    id          bigint      NOT NULL PRIMARY KEY,
    name        text        NOT NULL,
    exported_at timestamptz NOT NULL DEFAULT now(),
    task_count  bigint
);
